"""Build Sources/LauncherCore/EmojiData.swift from two MIT-licensed npm packages.

Download and unpack each package into its own folder, then run from the repository root:
    python scripts/make_emoji_data.py <emojilib package dir> <unicode-emoji-json package dir>

Sources: emojilib 4.0.3 (keywords) and unicode-emoji-json 0.9.0 (names, groups, order,
skin tone support), both by Mu-An Chiou. See THIRD_PARTY_NOTICES.md.
"""
import json
import sys
from pathlib import Path

GROUPS = ["Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink",
          "Travel & Places", "Activities", "Objects", "Symbols", "Flags"]


def main(emojilib, unicode_json):
    keywords = json.loads((Path(emojilib) / "dist/emoji-en-US.json").read_text())
    data = json.loads((Path(unicode_json) / "data-by-emoji.json").read_text())
    order = json.loads((Path(unicode_json) / "data-ordered-emoji.json").read_text())
    lines = []
    for symbol in order:
        info = data[symbol]
        name = info["name"]
        name_words = set(name.lower().replace(":", " ").split())
        extra = []
        for word in keywords.get(symbol, [])[1:]:  # the first keyword is the slug
            word = word.lower().replace("_", " ").strip()
            if word and word not in name_words and word not in extra and "\t" not in word:
                extra.append(word)
        fields = [symbol, str(GROUPS.index(info["group"])), "1" if info["skin_tone_support"] else "0", name, "|".join(extra)]
        assert all("\t" not in f and "\n" not in f and '"#' not in f for f in fields), symbol
        lines.append("\t".join(fields))
    body = "\n".join(lines)
    swift = (
        "// Generated by scripts/make_emoji_data.py. Do not edit.\n"
        "// Data: emojilib 4.0.3 and unicode-emoji-json 0.9.0, MIT, Mu-An Chiou.\n"
        "// One emoji a line: symbol, group index, skin tones (1 or 0), name, keywords split by |.\n\n"
        "enum EmojiData {\n"
        f"    static let groups = {json.dumps(GROUPS, ensure_ascii=False)}\n"
        f"    static let raw = #\"\"\"\n{body}\n\"\"\"#\n"
        "}\n"
    )
    Path("Sources/LauncherCore/EmojiData.swift").write_text(swift)
    print(f"ok {len(lines)} emoji")


if __name__ == "__main__":
    main(*sys.argv[1:3])
