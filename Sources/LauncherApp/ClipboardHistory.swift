import AppKit
import LauncherCore

/// Session-only text history. No disk storage or initial pasteboard harvest.
final class ClipboardHistory {
    struct Entry { let id: String; let text: String; let date: Date }
    private(set) var enabled = false
    private(set) var entries: [Entry] = []
    private var lastChange: Int
    private let pasteboard: NSPasteboard
    private let now: () -> Date
    private var suppressUntil = Date.distantPast
    // Pasteboard does not reliably identify its writer. Discard ambiguous changes
    // around every application transition instead of attributing them to the new app.
    func applicationChanged() { lastChange = pasteboard.changeCount; suppressUntil = now().addingTimeInterval(1) }
    init(pasteboard: NSPasteboard = .general, now: @escaping () -> Date = Date.init) {
        self.pasteboard = pasteboard; self.now = now; lastChange = pasteboard.changeCount
    }
    func setEnabled(_ value: Bool) { enabled = value; lastChange = pasteboard.changeCount }
    func clear() { entries.removeAll(); lastChange = pasteboard.changeCount }
    func copy(_ text: String) -> Bool {
        pasteboard.clearContents()
        let copied = pasteboard.setString(text, forType: .string)
        lastChange = pasteboard.changeCount
        return copied
    }
    func tick(frontmostBundleID: String?) {
        entries.removeAll { now().timeIntervalSince($0.date) > 86400 }
        guard enabled, lastChange != pasteboard.changeCount else { return }
        lastChange = pasteboard.changeCount
        guard now() >= suppressUntil else { return }
        let excluded = ["com.1password.1password", "com.agilebits.onepassword7", "com.apple.Passwords", "com.bitwarden.desktop", "com.lastpass.LastPass"]
        guard !excluded.contains(frontmostBundleID ?? "") else { return }
        let types = (pasteboard.types ?? []).map { $0.rawValue.lowercased() }
        guard !types.contains(where: { $0.contains("concealed") || $0.contains("transient") || $0.contains("autogenerated") || $0.contains("password") }) else { return }
        guard let text = pasteboard.string(forType: .string), !text.isEmpty, text.utf8.count <= 16384 else { return }
        entries.removeAll { $0.text == text }
        entries.insert(Entry(id: UUID().uuidString, text: text, date: now()), at: 0)
        if entries.count > 50 { entries.removeLast(entries.count - 50) }
    }
    func matching(_ query: String) -> [Entry] {
        entries.filter { query.isEmpty || $0.text.localizedCaseInsensitiveContains(query) }
    }

    static func runChecks() {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        var date = Date()
        let history = ClipboardHistory(pasteboard: board, now: { date })
        func put(_ value: String) { board.clearContents(); board.setString(value, forType: .string) }
        put("before-opt-in")
        history.tick(frontmostBundleID: nil)
        precondition(history.entries.isEmpty, "off by default")
        history.setEnabled(true); history.tick(frontmostBundleID: nil)
        precondition(history.entries.isEmpty, "must not harvest previous clipboard")
        put("safe-test"); history.tick(frontmostBundleID: nil)
        precondition(history.matching("SAFE").count == 1, "search")
        put("excluded-password"); history.tick(frontmostBundleID: "com.1password.1password")
        precondition(history.entries.count == 1, "password source exclusion")
        put("concealed"); board.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")); history.tick(frontmostBundleID: nil)
        precondition(history.entries.count == 1, "concealed type exclusion")
        put(String(repeating: "x", count: 17000)); history.tick(frontmostBundleID: nil)
        precondition(history.entries.count == 1, "size cap")
        for index in 0..<55 { put("test-\(index)"); history.tick(frontmostBundleID: nil) }
        precondition(history.entries.count == 50, "item cap")
        put("test-54"); history.tick(frontmostBundleID: nil)
        precondition(history.entries.count == 50, "dedup")
        history.setEnabled(false); put("paused"); history.tick(frontmostBundleID: nil)
        precondition(history.matching("paused").isEmpty, "pause")
        date = date.addingTimeInterval(86401); history.tick(frontmostBundleID: nil)
        precondition(history.entries.isEmpty, "expiry")
        history.setEnabled(true); put("clear-me"); history.tick(frontmostBundleID: nil); history.clear()
        precondition(history.entries.isEmpty, "clear")
        put("switch-race"); history.applicationChanged(); history.tick(frontmostBundleID: nil)
        put("switch-window"); history.tick(frontmostBundleID: nil)
        precondition(history.entries.isEmpty, "discard ambiguous app-transition copies")
        print("PASS 12 clipboard checks on isolated named pasteboard; system clipboard untouched")
    }
}
